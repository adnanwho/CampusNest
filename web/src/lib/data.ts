function availabilityStatus(occupied: number, capacity: number): "AVAILABLE" | "FILLING_FAST" | "ALMOST_FULL" | "FULL" {
  const ratio = occupied / capacity;
  if (ratio >= 1) return "FULL";
  if (ratio >= 0.8) return "ALMOST_FULL";
  if (ratio >= 0.5) return "FILLING_FAST";
  return "AVAILABLE";
}

